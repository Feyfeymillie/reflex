"""Train a PLACEHOLDER XGBoost model on SYNTHETIC data so the app runs end to end.

This is not the team's DHS model and must never be presented as clinically meaningful.
When the real model is ready, overwrite model.json and model_meta.json (same feature names
as features.json) and restart the app. Nothing else changes.

    python model/train_synthetic_model.py
"""
import json
from pathlib import Path

import numpy as np
import xgboost as xgb

HERE = Path(__file__).resolve().parent
FEATURES = [f["name"] for f in json.loads((HERE / "features.json").read_text())["features"]]


def synth(n, rng):
    age = rng.normal(26, 6.5, n).clip(13, 49).round()
    ga = rng.uniform(8, 40, n).round()
    gravida = (rng.poisson(1.8, n) + 1).clip(1, 12)
    parity = np.minimum(gravida - 1, rng.binomial(gravida - 1, 0.9))
    anc = np.minimum(rng.poisson(ga / 10), 8)
    multi = gravida > 1
    pe = (rng.random(n) < 0.06) & multi
    sb = (rng.random(n) < 0.05) & multi
    cs = (rng.random(n) < 0.08) & multi
    pph = (rng.random(n) < 0.05) & multi
    sys_ = rng.normal(116, 12, n) + 18 * pe + rng.normal(0, 1, n) * 10 * (rng.random(n) < 0.1)
    dia = sys_ * 0.64 + rng.normal(0, 6, n)
    muac = rng.normal(26, 3, n).clip(16, 40)
    ds = rng.poisson(0.15 + 0.6 * pe, n).clip(0, 6)

    X = np.column_stack([age, ga, gravida, parity, anc, pe, sb, cs, pph, sys_.round(), dia.round(), muac.round(1), ds]).astype(float)
    # knock out some optional measurements, as in the field
    X[rng.random(n) < 0.15, FEATURES.index("bp_sys")] = np.nan
    X[np.isnan(X[:, FEATURES.index("bp_sys")]), FEATURES.index("bp_dia")] = np.nan
    X[rng.random(n) < 0.4, FEATURES.index("muac")] = np.nan

    logit = (-3.2 + 0.045 * np.maximum(age - 34, 0) * 3 + 0.9 * (age < 18)
             + 1.3 * pe + 1.0 * sb + 0.5 * cs + 0.8 * pph
             + 0.06 * np.maximum(sys_ - 130, 0) + 0.08 * np.maximum(dia - 85, 0)
             + 0.6 * (anc == 0) * (ga > 20) + 0.25 * np.maximum(parity - 4, 0)
             + 0.7 * (muac < 23) + 0.9 * ds)
    y = (rng.random(n) < 1 / (1 + np.exp(-logit))).astype(int)
    return X, y


def auc(y, p):
    order = np.argsort(p)
    ranks = np.empty(len(p)); ranks[order] = np.arange(1, len(p) + 1)
    pos = y == 1
    return (ranks[pos].sum() - pos.sum() * (pos.sum() + 1) / 2) / (pos.sum() * (~pos).sum())


def main():
    rng = np.random.default_rng(42)
    X, y = synth(12000, rng)
    split = 9000
    dtrain = xgb.DMatrix(X[:split], label=y[:split], feature_names=FEATURES)
    dtest = xgb.DMatrix(X[split:], label=y[split:], feature_names=FEATURES)
    booster = xgb.train({"objective": "binary:logistic", "max_depth": 3, "eta": 0.1,
                         "subsample": 0.9, "eval_metric": "auc", "nthread": 4},
                        dtrain, num_boost_round=150)
    test_auc = auc(y[split:], booster.predict(dtest))
    booster.save_model(HERE / "model.json")
    meta = {
        "model_version": "synthetic-placeholder-0.1",
        "trained_on": "SYNTHETIC data generated by train_synthetic_model.py (not real patients)",
        "label": "synthetic adverse pregnancy outcome",
        "test_auc_on_synthetic": round(float(test_auc), 3),
        "xgboost_version": xgb.__version__,
        "bands": {"medium": 0.15, "high": 0.35},
        "features": FEATURES,
    }
    (HERE / "model_meta.json").write_text(json.dumps(meta, indent=2))
    print(json.dumps(meta, indent=2))


if __name__ == "__main__":
    main()
